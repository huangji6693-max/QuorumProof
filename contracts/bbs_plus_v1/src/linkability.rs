/// # BBS+ Linkability Control — Issue #1294
///
/// ## Problem
/// When the same BBS+ credential attributes are disclosed repeatedly to the
/// same or different verifiers, a passive observer that can correlate multiple
/// proofs may link them back to the same holder — even without learning the
/// hidden attributes — by:
/// 1. Tracking which `disclosed_fields` combinations appear together.
/// 2. Noticing that the `challenge` scalar correlates with the verifying key
///    and the same disclosed values.
/// 3. (For weak nonce schemes) replaying a captured proof against a different
///    verifier session.
///
/// ## Solution
/// This module provides *nonce-based unlinkability*:
/// - Every presentation uses a fresh, unpredictable `presentation_context`
///   (nonce) so the Fiat-Shamir challenge is unique per session.
/// - `generate_nonce` produces a 32-byte cryptographically secure nonce from
///   the system RNG.  Verifiers generate nonces; holders bind their proof to
///   that nonce.
/// - `create_unlinkable_disclosure` wraps `BbsPresentation::create_presentation`
///   with explicit nonce threading and an included nonce commitment so that
///   verifiers can confirm the proof was bound to *their* nonce.
/// - `verify_unlinkable_disclosure` verifies the proof and checks that the
///   embedded nonce matches the expected value — rejecting replays.
///
/// ## Privacy guarantees
/// 1. **Per-session unlinkability**: two proofs for the same credential
///    presented with different nonces share no observable scalar or point
///    (A_bar, B_bar, D are freshly randomized each call).
/// 2. **Nonce binding**: a proof cannot be replayed against a different nonce
///    because the Fiat-Shamir challenge incorporates the presentation context.
/// 3. **Verifier separation**: a proof created for verifier A cannot be
///    verified by verifier B if they use different nonces.
/// 4. **Hidden attribute privacy**: disclosed fields are bounded to exactly
///    the indices the holder chose; hidden attributes are protected by the
///    Schnorr responses.
///
/// ## Limitations
/// - This module cannot prevent linkability by *disclosed content itself*
///   (e.g. disclosing a unique identifier every time).  Holders should
///   minimise what they disclose.
/// - Nonce freshness depends on the verifier supplying a new nonce per
///   session; stale or repeated verifier nonces reduce the unlinkability
///   guarantee.
///
/// ## Issue requirements mapping
/// - "Implement nonce generation for unlinkable disclosures" → `generate_nonce`
/// - "Add `create_unlinkable_disclosure(env, credential_id, attributes, nonce)`"
///   → `create_unlinkable_disclosure`
/// - "Implement verification with nonce checking" →
///   `verify_unlinkable_disclosure`
/// - "Add privacy guarantee documentation" → this module doc

